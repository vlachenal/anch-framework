#pragma once

#include <algorithm>
#include <cstdint>
#include <cstring>
#include <string>
#include <utility>

#include <thrift/transport/TVirtualTransport.h>

#include "rest/client.hpp"
#include "rest/httpError.hpp"
#include "rest/thriftCodec.hpp"

namespace anch::rest {

  /*!
   * Thrift transport over an anch-rest client (header only: link \c anch::rest-client ): calls are sent
   * with <tt>POST path</tt> on client base URL (client filters, authentication and transport apply), to
   * an API with \ref installThrift or any Thrift HTTP server. Clients generated by
   * <tt>thrift --gen cpp</tt> use it as is:
   * \code{.cpp}
auto transport = std::make_shared<anch::rest::ThriftTransport>(client, "/thrift/pets");
pets::PetStoreClient pets(anch::rest::thriftProtocol(anch::rest::ThriftProtocol::BINARY, transport));
pets::Pet pet;
pets.getPet(pet, 1);
   * \endcode
   * The protocol given to the transport sets the request content type (it has to be the one of the
   * client protocol). Responses with status greater or equal to \c 400 raise \ref HttpError . A
   * transport is used by one client at a time.
   *
   * \author Vincent Lachenal
   *
   * \since 0.2
   */
  class ThriftTransport: public apache::thrift::transport::TVirtualTransport<ThriftTransport> {

    // Attributes +
  private:
    /*! anch-rest client */
    anch::rest::Client& _client;

    /*! Service path */
    std::string _path;

    /*! Request content type */
    std::string _contentType;

    /*! Message being written */
    std::string _request;

    /*! Response being read */
    std::string _response;

    /*! Response read position */
    std::size_t _position;
    // Attributes -

    // Constructors +
  public:
    /*!
     * \ref ThriftTransport constructor
     *
     * \param client the anch-rest client (it has to outlive the transport)
     * \param path the service path
     * \param protocol the protocol of the Thrift client (request content type)
     */
    ThriftTransport(anch::rest::Client& client, std::string path, anch::rest::ThriftProtocol protocol = anch::rest::ThriftProtocol::BINARY);
    // Constructors -

    // Methods +
  public:
    /*!
     * Transport is always open (connections are managed by the anch-rest transport)
     *
     * \return \c true
     */
    virtual bool isOpen() const override;

    /*!
     * Nothing to open
     */
    virtual void open() override;

    /*!
     * Nothing to close
     */
    virtual void close() override;

    /*!
     * Read response
     *
     * \param buffer the buffer to fill
     * \param length the maximum length
     *
     * \return the number of bytes read, \c 0 at the end of the response
     */
    uint32_t read(uint8_t* buffer, uint32_t length);

    /*!
     * Write request
     *
     * \param buffer the data
     * \param length the data length
     */
    void write(const uint8_t* buffer, uint32_t length);

    /*!
     * Send request and receive response
     *
     * \throw HttpError when response status is greater or equal to \c 400
     * \throw TransportError on network error
     */
    virtual void flush() override;
    // Methods -

  };

}

#include "rest/impl/thriftTransport.hpp"
