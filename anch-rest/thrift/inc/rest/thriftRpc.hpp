namespace anch::rest {

  /*!
   * Install Thrift service in API (header only: link \c anch::rest-server ): <tt>POST path</tt>
   * processes Thrift messages with the processor generated by <tt>thrift --gen cpp</tt> , as Thrift
   * \c THttpServer . The protocol is chosen with the request \c Content-Type
   * ( \c application/x-thrift and \c application/vnd.apache.thrift.binary , \c .compact , \c .json ),
   * the response has the same content type. Declared exceptions and unknown methods are answered by the
   * processor (Thrift application exceptions), unsupported content types with \c 415 , invalid
   * messages with \c 400 .
   * \snippet{trimleft} anch-rest/examples/thrift.cpp thrift rpc
   *
   * \param api the API
   * \param path the path pattern
   * \param processor the Thrift processor
   * \param maxMessageSize the maximum request message size (default: 16 MiB)
   *
   * \since 0.2
   */
  void installThrift(anch::rest::Api& api, std::string_view path, std::shared_ptr<apache::thrift::TProcessor> processor,
		     std::size_t maxMessageSize = 16 * 1024 * 1024);

}

