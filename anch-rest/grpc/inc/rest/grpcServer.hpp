#pragma once

#include <map>
#include <memory>
#include <string>
#include <string_view>

#include <grpcpp/security/server_credentials.h>
#include <grpcpp/server.h>
#include <grpcpp/server_builder.h>

#include "rest/rpcService.hpp"

namespace anch::rest {

  /*!
   * gRPC server (HTTP/2) for \ref RpcService : the same services can be installed in an anch-rest API
   * ( \ref installRpc , Connect and gRPC-Web) and in a gRPC server, for native gRPC clients (stubs
   * generated by \c grpc_cpp_plugin ).
   * \code{.cpp}
anch::rest::GrpcServer server;
server.addService(service).listen("0.0.0.0:50051");
server.start();
// ...
server.shutdown();
   * \endcode
   * Methods are unary: the first request message is processed. \ref RpcError is sent with its code and
   * message ( \c UNIMPLEMENTED for unknown methods), request metadata are given in \ref RpcContext ,
   * response metadata are sent as initial metadata. Services have to outlive the server.
   *
   * \author Vincent Lachenal
   *
   * \since 0.2
   */
  class GrpcServer {

    /*! Generic service which dispatches calls to RPC services */
    class Dispatcher;

    // Attributes +
  private:
    /*! gRPC server builder */
    grpc::ServerBuilder _builder;

    /*! RPC services by name */
    std::map<std::string, const anch::rest::RpcService*, std::less<>> _services;

    /*! Generic service */
    std::unique_ptr<Dispatcher> _dispatcher;

    /*! Server */
    std::unique_ptr<grpc::Server> _server;

    /*! Port selected by the first listening address */
    int _port;
    // Attributes -

    // Constructors +
  public:
    /*!
     * \ref GrpcServer constructor
     */
    GrpcServer();

    /*! Prohibit \ref GrpcServer copy */
    GrpcServer(const GrpcServer&) = delete;
    // Constructors -

    // Destructor +
  public:
    /*!
     * \ref GrpcServer destructor: server is shut down
     */
    virtual ~GrpcServer();
    // Destructor -

    // Methods +
  public:
    /*!
     * Add RPC service (before \ref start )
     *
     * \param service the service
     *
     * \return \c this
     *
     * \throw std::invalid_argument when a service with the same name already exists
     */
    GrpcServer& addService(const anch::rest::RpcService& service);

    /*!
     * Add listening address (before \ref start )
     *
     * \param address the address ( \c 0.0.0.0:50051 , \c 127.0.0.1:0 for a free port)
     * \param credentials the credentials (insecure by default)
     *
     * \return \c this
     */
    GrpcServer& listen(const std::string& address,
		       std::shared_ptr<grpc::ServerCredentials> credentials = grpc::InsecureServerCredentials());

    /*!
     * Get gRPC server builder, to set other options (before \ref start )
     *
     * \return the builder
     */
    grpc::ServerBuilder& builder() noexcept;

    /*!
     * Start server
     *
     * \return the port of the first listening address
     *
     * \throw std::runtime_error when server can not be started
     */
    int start();

    /*!
     * Wait for server shutdown
     */
    void wait();

    /*!
     * Shut down server: running calls are completed
     */
    void shutdown();

    /*! Prohibit \ref GrpcServer copy */
    GrpcServer& operator=(const GrpcServer&) = delete;
    // Methods -

    // Accessors +
  public:
    /*!
     * Get the port of the first listening address
     *
     * \return the port, \c 0 before \ref start
     */
    int getPort() const noexcept;
    // Accessors -

  };

}
