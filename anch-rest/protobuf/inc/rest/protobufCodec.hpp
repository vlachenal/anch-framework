#pragma once

#include "anch-rest-protobuf-export.hpp"

#include <concepts>
#include <istream>
#include <ostream>
#include <string>
#include <string_view>

#include <google/protobuf/message.h>

#include "rest/codec.hpp"
#include "rest/mediaType.hpp"

namespace anch::rest {

  /*!
   * Protocol Buffers message: generated by \c protoc ( \c google::protobuf::Message )
   *
   * \tparam T the message type
   *
   * \since 0.2
   */
  template<typename T>
  concept ProtobufMessage = std::derived_from<T, google::protobuf::Message>;

  /*!
   * \c application/x-protobuf codec: Protocol Buffers binary encoding of \c protoc messages.
   * Invalid messages raise \c std::invalid_argument ( \c 400 on server side).
   * \snippet{trimleft} anch-rest/examples/protobuf.cpp protobuf codec
   *
   * \snippet{trimleft} anch-rest/examples/protobuf.cpp protobuf client
   *
   * \author Vincent Lachenal
   *
   * \since 0.2
   */
  struct ANCH_REST_PROTOBUF_EXPORT Protobuf {

    /*!
     * Media type
     *
     * \return \c application/x-protobuf
     */
    static std::string_view mediaType() noexcept;

    /*!
     * Write message
     *
     * \param value the message
     * \param out the output stream
     *
     * \throw std::runtime_error when message can not be written
     */
    template<anch::rest::ProtobufMessage T>
    static void serialize(const T& value, std::ostream& out);

    /*!
     * Read message (body size is bounded by \ref maxBodySize )
     *
     * \param value the message to fill
     * \param input the input stream
     * \param side the side
     *
     * \throw std::invalid_argument when message is invalid
     * \throw ContentTooLarge when body is larger than \ref maxBodySize
     */
    template<anch::rest::ProtobufMessage T>
    static void deserialize(T& value, std::istream& input, anch::rest::Side side);

    /*!
     * Write message (any \c protoc message)
     *
     * \param message the message
     * \param out the output stream
     *
     * \throw std::runtime_error when message can not be written
     */
    static void write(const google::protobuf::Message& message, std::ostream& out);

    /*!
     * Read message (any \c protoc message)
     *
     * \param message the message to fill
     * \param input the input stream
     *
     * \throw std::invalid_argument when message is invalid
     */
    static void read(google::protobuf::Message& message, std::istream& input);

    /*!
     * Read message (any \c protoc message)
     *
     * \param message the message to fill
     * \param data the serialized message
     *
     * \throw std::invalid_argument when message is invalid
     *
     * \since 0.3
     */
    static void read(google::protobuf::Message& message, std::string_view data);

  };

  /*!
   * \c application/json codec for \c protoc messages: Protocol Buffers JSON mapping (field names in
   * lowerCamelCase, 64 bits integers as strings, ...). Unknown fields are refused on server side and
   * ignored on client side (server responses are trusted). Invalid messages raise
   * \c std::invalid_argument ( \c 400 on server side).
   *
   * \author Vincent Lachenal
   *
   * \since 0.2
   */
  struct ANCH_REST_PROTOBUF_EXPORT ProtobufJson {

    /*!
     * Media type
     *
     * \return \c application/json
     */
    static std::string_view mediaType() noexcept;

    /*!
     * Write message
     *
     * \param value the message
     * \param out the output stream
     * \param side the side which writes message
     *
     * \throw std::runtime_error when message can not be written
     */
    template<anch::rest::ProtobufMessage T>
    static void serialize(const T& value, std::ostream& out, anch::rest::Side side);

    /*!
     * Read message
     *
     * \param value the message to fill
     * \param input the input stream
     * \param side the side which reads message
     *
     * \throw std::invalid_argument when message is invalid
     * \throw ContentTooLarge when body is larger than \ref maxBodySize
     */
    template<anch::rest::ProtobufMessage T>
    static void deserialize(T& value, std::istream& input, anch::rest::Side side);

    /*!
     * Get JSON of a message
     *
     * \param message the message
     *
     * \return the JSON text
     *
     * \throw std::runtime_error when message can not be written
     */
    static std::string toJson(const google::protobuf::Message& message);

    /*!
     * Read message from JSON
     *
     * \param message the message to fill
     * \param json the JSON text
     * \param ignoreUnknownFields ignore unknown fields
     *
     * \throw std::invalid_argument when JSON is not a valid message
     */
    static void fromJson(google::protobuf::Message& message, std::string_view json, bool ignoreUnknownFields);

  };

}

